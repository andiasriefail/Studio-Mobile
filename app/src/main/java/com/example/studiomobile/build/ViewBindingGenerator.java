package com.example.studiomobile.build;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import javax.xml.parsers.DocumentBuilder;
import javax.xml.parsers.DocumentBuilderFactory;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

/**
 * Generates the {@code XxxBinding} classes of Android View Binding from layout XML, in the same shape AGP produces
 * (inflate / bind / getRoot, nullable fields for views that are missing in some layout variant, include bindings, merge roots).
 * Output is a map from relative source path to Java source; nothing is written here.
 *
 * Not covered on purpose: Data Binding layouts ({@code <layout>} root; they are skipped), custom binding adapters, and
 * {@code <include>} of layouts that are not part of the project (their field becomes a plain {@code View}).
 */
public final class ViewBindingGenerator {
    private static final String ID = "android:id";
    private static final Set<String> JAVA_KEYWORDS = new HashSet<>(Arrays.asList(
        "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue", "default", "do", "double", "else",
        "enum", "extends", "final", "finally", "float", "for", "goto", "if", "implements", "import", "instanceof", "int", "interface", "long",
        "native", "new", "package", "private", "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized",
        "this", "throw", "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null", "rootView", "id", "missingId"));
    private static final Set<String> VIEW_PACKAGE = new HashSet<>(Arrays.asList("View", "ViewGroup", "ViewStub", "TextureView", "SurfaceView"));

    /** One view with an id inside one layout. */
    private static final class Entry {
        String field, idName, type, includeLayout; boolean nullable, root;
    }

    /** One layout name merged over its qualifier directories (layout, layout-land, ...). */
    private static final class Layout {
        final String name; final ProjectModules.Module module;
        String rootType = "android.view.View"; boolean merge;
        final Map<String, Entry> entries = new LinkedHashMap<>();
        Layout(String name, ProjectModules.Module module) { this.name = name; this.module = module; }
        String bindingClass() { return pascal(name) + "Binding"; }
        String bindingPackage() { return module.namespace + ".databinding"; }
        String qualifiedBinding() { return bindingPackage() + "." + bindingClass(); }
    }

    private final boolean useAnnotations;
    private final boolean needViewBindingShim;
    private final List<String> warnings = new ArrayList<>();

    /**
     * @param useAnnotations      androidx.annotation is on the classpath, so @NonNull/@Nullable are emitted
     * @param needViewBindingShim androidx.viewbinding.ViewBinding is not on the classpath, so a tiny stand-in is generated
     */
    public ViewBindingGenerator(boolean useAnnotations, boolean needViewBindingShim) {
        this.useAnnotations = useAnnotations; this.needViewBindingShim = needViewBindingShim;
    }

    public List<String> getWarnings() { return Collections.unmodifiableList(warnings); }

    /** @param modules every module that enables viewBinding (needed together so includes can cross module borders) */
    public Map<String, String> generate(List<ProjectModules.Module> modules) throws IOException {
        Map<String, String> files = new LinkedHashMap<>();
        Map<ProjectModules.Module, Map<String, Layout>> parsed = new LinkedHashMap<>();
        for (ProjectModules.Module module : modules) {
            if (module.namespace == null) { warnings.add("Module " + module.path + " enables viewBinding but has no namespace/package; skipped."); continue; }
            parsed.put(module, parseModule(module));
        }
        for (Map.Entry<ProjectModules.Module, Map<String, Layout>> module : parsed.entrySet()) {
            for (Layout layout : module.getValue().values()) {
                String source = render(layout, module.getKey(), parsed);
                files.put(layout.bindingPackage().replace('.', '/') + "/" + layout.bindingClass() + ".java", source);
            }
        }
        if (!files.isEmpty() && needViewBindingShim) {
            files.put("androidx/viewbinding/ViewBinding.java",
                "package androidx.viewbinding;\n\n/** Stand-in generated by Studio Mobile because androidx.databinding:viewbinding is not a dependency. */\n"
                + "public interface ViewBinding {\n  android.view.View getRoot();\n}\n");
        }
        return files;
    }

    // -------------------------------------------------------------------------------------------------------------------------
    // Parsing
    // -------------------------------------------------------------------------------------------------------------------------

    private Map<String, Layout> parseModule(ProjectModules.Module module) throws IOException {
        Map<String, List<File>> byName = new LinkedHashMap<>();
        for (File resources : module.resourceDirectories()) {
            File[] directories = resources.listFiles();
            if (directories == null) continue;
            Arrays.sort(directories);
            for (File directory : directories) {
                String directoryName = directory.getName();
                if (!directory.isDirectory() || !(directoryName.equals("layout") || directoryName.startsWith("layout-"))) continue;
                File[] files = directory.listFiles((parent, name) -> name.endsWith(".xml"));
                if (files == null) continue;
                Arrays.sort(files);
                for (File file : files) {
                    String name = file.getName().substring(0, file.getName().length() - 4);
                    if (!byName.containsKey(name)) byName.put(name, new ArrayList<File>());
                    // The default directory first so its ids define the order of the fields.
                    if (directoryName.equals("layout")) byName.get(name).add(0, file); else byName.get(name).add(file);
                }
            }
        }
        Map<String, Layout> result = new LinkedHashMap<>();
        for (Map.Entry<String, List<File>> item : byName.entrySet()) {
            Layout merged = null;
            List<Layout> variants = new ArrayList<>();
            boolean skipped = false;
            for (File file : item.getValue()) {
                Layout variant = parseFile(item.getKey(), file, module);
                if (variant == null) { skipped = true; break; }
                variants.add(variant);
            }
            if (skipped || variants.isEmpty()) continue;
            merged = variants.get(0);
            for (int i = 1; i < variants.size(); i++) mergeVariant(merged, variants.get(i));
            for (Entry entry : merged.entries.values()) {
                // An id missing from at least one qualifier directory is nullable.
                for (Layout variant : variants) if (!variant.entries.containsKey(entry.idName)) entry.nullable = true;
            }
            assignFieldNames(merged);
            result.put(item.getKey(), merged);
        }
        return result;
    }

    private Layout parseFile(String name, File file, ProjectModules.Module module) throws IOException {
        Document document;
        try {
            DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
            factory.setNamespaceAware(false);
            DocumentBuilder builder = factory.newDocumentBuilder();
            document = builder.parse(file);
        } catch (Exception failure) {
            warnings.add(module.path + ": " + file.getName() + " could not be parsed for view binding (" + failure.getMessage() + "); skipped.");
            return null;
        }
        Element root = document.getDocumentElement();
        if (root == null || root.getTagName().equals("layout")) return null; // Data Binding layout
        if ("true".equals(root.getAttribute("tools:viewBindingIgnore"))) return null;
        Layout layout = new Layout(name, module);
        layout.merge = root.getTagName().equals("merge");
        layout.rootType = layout.merge ? "android.view.View" : typeOf(root);
        collect(root, true, layout);
        return layout;
    }

    private void collect(Element element, boolean isRoot, Layout layout) {
        String tag = element.getTagName();
        String idAttribute = element.getAttribute(ID);
        boolean ignored = "true".equals(element.getAttribute("tools:viewBindingIgnore"));
        if (!ignored && !idAttribute.isEmpty() && (idAttribute.startsWith("@+id/") || idAttribute.startsWith("@id/"))) {
            String idName = idAttribute.substring(idAttribute.indexOf('/') + 1);
            if (!layout.entries.containsKey(idName) && !idName.isEmpty()) {
                Entry entry = new Entry();
                entry.idName = idName; entry.root = isRoot && !layout.merge;
                if (tag.equals("include")) {
                    String target = element.getAttribute("layout");
                    entry.includeLayout = target.startsWith("@layout/") ? target.substring("@layout/".length()) : null;
                    entry.type = "android.view.View";
                } else entry.type = typeOf(element);
                layout.entries.put(idName, entry);
            }
        }
        if (tag.equals("include")) return;
        NodeList children = element.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            Node child = children.item(i);
            if (child.getNodeType() == Node.ELEMENT_NODE) collect((Element) child, false, layout);
        }
    }

    private static String typeOf(Element element) {
        String tag = element.getTagName();
        if (tag.equals("view")) { String named = element.getAttribute("class"); return named.isEmpty() ? "android.view.View" : named.replace('$', '.'); }
        if (tag.equals("fragment") || tag.equals("include") || tag.equals("merge")) return "android.view.View";
        if (tag.indexOf('.') >= 0) return tag.replace('$', '.');
        if (VIEW_PACKAGE.contains(tag)) return "android.view." + tag;
        if (tag.equals("WebView")) return "android.webkit.WebView";
        return "android.widget." + tag;
    }

    private void mergeVariant(Layout base, Layout other) {
        if (!base.rootType.equals(other.rootType)) base.rootType = "android.view.View";
        base.merge |= other.merge;
        for (Entry entry : other.entries.values()) {
            Entry existing = base.entries.get(entry.idName);
            if (existing == null) { entry.nullable = true; base.entries.put(entry.idName, entry); continue; }
            if (!existing.type.equals(entry.type)) existing.type = "android.view.View";
            if (existing.includeLayout != null && !existing.includeLayout.equals(entry.includeLayout)) existing.includeLayout = null;
            existing.root &= entry.root;
        }
    }

    private static void assignFieldNames(Layout layout) {
        Set<String> used = new HashSet<>();
        for (Entry entry : layout.entries.values()) {
            String name = camel(entry.idName);
            if (JAVA_KEYWORDS.contains(name)) name = name + "_";
            while (!used.add(name)) name = name + "_";
            entry.field = name;
        }
    }

    // -------------------------------------------------------------------------------------------------------------------------
    // Rendering
    // -------------------------------------------------------------------------------------------------------------------------

    private String nonNull() { return useAnnotations ? "@androidx.annotation.NonNull " : ""; }
    private String nullable() { return useAnnotations ? "@androidx.annotation.Nullable " : ""; }

    private String render(Layout layout, ProjectModules.Module module, Map<ProjectModules.Module, Map<String, Layout>> all) {
        String r = module.namespace + ".R";
        String self = layout.bindingClass();
        // Resolve the field types: an include with an id becomes the included layout's binding class when it is part of the project.
        Map<Entry, String> types = new LinkedHashMap<>();
        for (Entry entry : layout.entries.values()) {
            String type = entry.type;
            if (entry.includeLayout != null) {
                Layout target = findLayout(entry.includeLayout, module, all);
                if (target != null && !target.merge) type = target.qualifiedBinding();
                else entry.includeLayout = null;
            }
            types.put(entry, type);
        }
        StringBuilder out = new StringBuilder();
        out.append("// Generated by Studio Mobile from res/layout/").append(layout.name).append(".xml. Do not edit.\n");
        out.append("package ").append(layout.bindingPackage()).append(";\n\n");
        out.append("public final class ").append(self).append(" implements androidx.viewbinding.ViewBinding {\n");
        String rootType = layout.merge ? "android.view.View" : layout.rootType;
        out.append("  ").append(nonNull()).append("private final ").append(rootType).append(" rootView;\n\n");
        for (Entry entry : layout.entries.values())
            out.append("  ").append(entry.nullable ? nullable() : nonNull()).append("public final ").append(types.get(entry)).append(' ').append(entry.field).append(";\n");
        out.append("\n  private ").append(self).append("(").append(nonNull()).append(rootType).append(" rootView");
        for (Entry entry : layout.entries.values()) out.append(", ").append(entry.nullable ? nullable() : nonNull()).append(types.get(entry)).append(' ').append(entry.field);
        out.append(") {\n    this.rootView = rootView;\n");
        for (Entry entry : layout.entries.values()) out.append("    this.").append(entry.field).append(" = ").append(entry.field).append(";\n");
        out.append("  }\n\n");
        out.append("  @Override\n  ").append(nonNull()).append("public ").append(rootType).append(" getRoot() {\n    return rootView;\n  }\n\n");

        out.append("  ").append(nonNull()).append("public static ").append(self).append(" inflate(").append(nonNull()).append("android.view.LayoutInflater inflater) {\n");
        out.append(layout.merge ? "    return inflate(inflater, null);\n  }\n\n" : "    return inflate(inflater, null, false);\n  }\n\n");
        if (layout.merge) {
            out.append("  ").append(nonNull()).append("public static ").append(self).append(" inflate(").append(nonNull()).append("android.view.LayoutInflater inflater, ")
               .append(nullable()).append("android.view.ViewGroup parent) {\n");
            out.append("    if (parent == null) {\n      throw new NullPointerException(\"parent\");\n    }\n");
            out.append("    inflater.inflate(").append(r).append(".layout.").append(layout.name).append(", parent);\n    return bind(parent);\n  }\n\n");
        } else {
            out.append("  ").append(nonNull()).append("public static ").append(self).append(" inflate(").append(nonNull()).append("android.view.LayoutInflater inflater, ")
               .append(nullable()).append("android.view.ViewGroup parent, boolean attachToParent) {\n");
            out.append("    android.view.View root = inflater.inflate(").append(r).append(".layout.").append(layout.name).append(", parent, false);\n");
            out.append("    if (attachToParent) {\n      parent.addView(root);\n    }\n    return bind(root);\n  }\n\n");
        }

        out.append("  ").append(nonNull()).append("public static ").append(self).append(" bind(").append(nonNull()).append("android.view.View rootView) {\n");
        out.append("    int id;\n    missingId: {\n");
        List<String> arguments = new ArrayList<>();
        for (Entry entry : layout.entries.values()) {
            String type = types.get(entry), name = entry.field;
            arguments.add(name);
            if (entry.root) { out.append("      ").append(type).append(' ').append(name).append(" = (").append(type).append(") rootView;\n"); continue; }
            out.append("      id = ").append(r).append(".id.").append(entry.idName).append(";\n");
            if (entry.includeLayout != null) {
                out.append("      android.view.View view_").append(name).append(" = rootView.findViewById(id);\n");
                if (!entry.nullable) out.append("      if (view_").append(name).append(" == null) {\n        break missingId;\n      }\n");
                out.append("      ").append(type).append(' ').append(name).append(" = ").append(entry.nullable ? "view_" + name + " == null ? null : " : "")
                   .append(type).append(".bind(view_").append(name).append(");\n");
            } else {
                out.append("      ").append(type).append(' ').append(name).append(" = rootView.findViewById(id);\n");
                if (!entry.nullable) out.append("      if (").append(name).append(" == null) {\n        break missingId;\n      }\n");
            }
        }
        out.append("      return new ").append(self).append("((").append(rootType).append(") rootView");
        for (String argument : arguments) out.append(", ").append(argument);
        out.append(");\n    }\n");
        out.append("    String missingId = rootView.getResources().getResourceName(id);\n");
        out.append("    throw new NullPointerException(\"Missing required view with ID: \".concat(missingId));\n  }\n}\n");
        return out.toString();
    }

    private static Layout findLayout(String name, ProjectModules.Module from, Map<ProjectModules.Module, Map<String, Layout>> all) {
        Map<String, Layout> own = all.get(from);
        if (own != null && own.containsKey(name)) return own.get(name);
        for (Map<String, Layout> other : all.values()) if (other.containsKey(name)) return other.get(name);
        return null;
    }

    // -------------------------------------------------------------------------------------------------------------------------
    // Names
    // -------------------------------------------------------------------------------------------------------------------------

    /** activity_main -> ActivityMain */
    static String pascal(String name) {
        StringBuilder out = new StringBuilder();
        for (String part : name.split("_")) if (!part.isEmpty()) out.append(part.substring(0, 1).toUpperCase(Locale.ROOT)).append(part.substring(1));
        return out.toString();
    }

    /** my_view_2 -> myView2 */
    static String camel(String name) {
        String pascal = pascal(name);
        return pascal.isEmpty() ? name : pascal.substring(0, 1).toLowerCase(Locale.ROOT) + pascal.substring(1);
    }
}
