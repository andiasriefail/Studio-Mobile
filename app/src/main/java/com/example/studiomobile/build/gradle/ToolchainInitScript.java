package com.example.studiomobile.build.gradle;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Arrays;

/**
 * The Gradle init script that makes {@code jvmToolchain(N)} / {@code java.toolchain} work on a device that has one JDK.
 *
 * <p>Gradle looks for a JDK with exactly the requested major, and only in places it knows (the JVM running Gradle, JAVA_HOME,
 * OS folders, SDKMAN and similar, org.gradle.java.installations.paths). Downloading one needs a resolver plugin, and the
 * downloaded desktop build could not run on Android anyway. On the device the only JDK is the one Studio Mobile started Gradle
 * with, so a request for an older major (jvmToolchain(11) with AGP 8, which runs on JDK 17) can never be found.
 *
 * <p>For a project whose request is LOWER than the running JDK, the script points the request at the running JDK and keeps the
 * requested language level: Java source/target compatibility and the Kotlin jvmTarget stay at N, so the class files are still
 * Java N. A request equal to the running JDK needs nothing, and a request higher than it cannot be built here (the planner
 * already raises the JDK for that, and reports a clear error when no JDK is high enough). Every step is guarded: a problem is
 * logged as a short warning (the technical reason goes to the info level only) and the build continues exactly as it would have without the script.
 * A Java level the project has not set yet is read as "not set" instead of failing, because the Android plugin only settles it later.
 */
public final class ToolchainInitScript {
    /** Written into the Gradle user home and passed with -I by {@link GradleRuntime#buildArguments(boolean)}. */
    public static final String FILE_NAME = "studio-toolchain-init.gradle";

    private ToolchainInitScript() { }

    /** The script text (Groovy). Kept as lines so it needs no text blocks and stays readable in diffs. */
    static String content() {
        return String.join("\n", Arrays.asList(
            "// Studio Mobile: maps a jvmToolchain(N) / java.toolchain request that is lower than the JDK running Gradle to that JDK.",
            "// Generated by the app on every build; changes are overwritten.",
            "def studioRunning = JavaVersion.current().majorVersion.toInteger()",
            "",
            "// Reads a value that the Android plugin may not have settled yet; null means it has not been set by the project.",
            "def studioRead = { Closure read ->",
            "    try { return read() } catch (Throwable ignored) { return null }",
            "}",
            "",
            "// The Kotlin jvmTarget followed the toolchain; put it back to the requested level.",
            "def studioPinKotlin = { Task task, int level, int running ->",
            "    String type = task.class.name",
            "    if (!type.startsWith('org.jetbrains.kotlin.gradle.tasks.KotlinCompile') || type.startsWith('org.jetbrains.kotlin.gradle.tasks.KotlinCompileCommon')) return",
            "    try {",
            "        def jvmTarget = task.compilerOptions.jvmTarget",
            "        def current = jvmTarget.getOrNull()",
            "        if (current != null && current.target == String.valueOf(running)) {",
            "            def targetClass = task.class.classLoader.loadClass('org.jetbrains.kotlin.gradle.dsl.JvmTarget')",
            "            jvmTarget.set(targetClass.getMethod('fromTarget', String).invoke(null, level == 8 ? '1.8' : String.valueOf(level)))",
            "        }",
            "    } catch (Throwable ignored) { }",
            "}",
            "",
            "allprojects { Project studioProject ->",
            "    studioProject.afterEvaluate { Project project ->",
            "        try {",
            "            def javaExt = project.extensions.findByName('java')",
            "            if (javaExt == null) return",
            "            def requested = javaExt.toolchain.languageVersion.getOrNull()",
            "            if (requested == null) return",
            "            int level = requested.asInt()",
            "            if (level >= studioRunning) return",
            "            javaExt.toolchain.languageVersion.set(org.gradle.jvm.toolchain.JavaLanguageVersion.of(studioRunning))",
            "            project.logger.lifecycle('[Studio] Java toolchain ' + level + ' is not installed on this device; building with JDK ' + studioRunning + ' at Java ' + level + '.')",
            "            def pinned = org.gradle.api.JavaVersion.toVersion(level)",
            "            def running = org.gradle.api.JavaVersion.toVersion(studioRunning)",
            "            try {",
            "                def android = project.extensions.findByName('android')",
            "                if (android != null) {",
            "                    def options = android.compileOptions",
            "                    def source = studioRead { options.sourceCompatibility }",
            "                    def target = studioRead { options.targetCompatibility }",
            "                    if (source == null || source == running) options.sourceCompatibility = pinned",
            "                    if (target == null || target == running) options.targetCompatibility = pinned",
            "                } else {",
            "                    def source = studioRead { javaExt.sourceCompatibility }",
            "                    def target = studioRead { javaExt.targetCompatibility }",
            "                    if (source == null || source == running) javaExt.sourceCompatibility = pinned",
            "                    if (target == null || target == running) javaExt.targetCompatibility = pinned",
            "                }",
            "            } catch (Throwable problem) {",
            "                project.logger.warn('[Studio] Could not keep Java level ' + level + ' for ' + project.path + '; the build continues with the default Java level.')",
            "                project.logger.info('[Studio] Java level detail: ' + problem)",
            "            }",
            "            project.tasks.configureEach { task -> studioPinKotlin(task, level, studioRunning) }",
            "        } catch (Throwable problem) {",
            "            project.logger.warn('[Studio] Could not map the Java toolchain request of ' + project.path + ' to JDK ' + studioRunning + '; the build continues without it.')",
            "            project.logger.info('[Studio] Java toolchain detail: ' + problem)",
            "        }",
            "    }",
            "}",
            ""));
    }

    /** Writes the script into the Gradle user home when it is missing or different. Null when it could not be written. */
    public static File ensure(File gradleUserHome) {
        try {
            if (!gradleUserHome.isDirectory() && !gradleUserHome.mkdirs()) return null;
            File file = new File(gradleUserHome, FILE_NAME);
            byte[] wanted = content().getBytes(StandardCharsets.UTF_8);
            if (!file.isFile() || !Arrays.equals(Files.readAllBytes(file.toPath()), wanted)) Files.write(file.toPath(), wanted);
            return file;
        } catch (Exception failure) {
            return null;
        }
    }
}
