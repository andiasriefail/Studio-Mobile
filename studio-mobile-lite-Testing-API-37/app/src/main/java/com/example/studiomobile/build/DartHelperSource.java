package com.example.studiomobile.build;

/**
 * Source of {@code studio.dart.StudioDart}, the small class that lets the Java/Kotlin code of an app start the Dart program packed
 * into it by {@link com.example.studiomobile.build.stages.DartAppStage}. It is written into the generated sources of the build, so
 * the app's own code can use it without any dependency.
 */
public final class DartHelperSource {
    private DartHelperSource() { }

    public static final String SOURCE = String.join("\n",
        "package studio.dart;",
        "",
        "import android.content.Context;",
        "import android.os.Handler;",
        "import android.os.Looper;",
        "import java.io.BufferedReader;",
        "import java.io.File;",
        "import java.io.FileOutputStream;",
        "import java.io.IOException;",
        "import java.io.InputStream;",
        "import java.io.InputStreamReader;",
        "import java.io.OutputStream;",
        "import java.nio.charset.StandardCharsets;",
        "import java.util.concurrent.ExecutorService;",
        "import java.util.concurrent.Executors;",
        "",
        "/**",
        " * Generated by Studio Mobile. Runs src/main/dart/main.dart, which was compiled into this app, on the Dart VM.",
        " * Everything the Dart program prints arrives in Listener.onLine; send() writes a line to its standard input.",
        " * Callbacks arrive on the main thread. Works on 64-bit ARM devices (arm64-v8a).",
        " */",
        "public final class StudioDart {",
        "    public interface Listener {",
        "        void onLine(String line);",
        "        void onExit(int exitCode);",
        "    }",
        "",
        "    private final Process process;",
        "    private final OutputStream input;",
        "    private final ExecutorService writer = Executors.newSingleThreadExecutor();",
        "",
        "    private StudioDart(Process process) {",
        "        this.process = process;",
        "        this.input = process.getOutputStream();",
        "    }",
        "",
        "    /** Starts the Dart program. Throws IOException with a readable reason when it cannot run on this device. */",
        "    public static StudioDart start(Context context, final Listener listener) throws IOException {",
        "        Context app = context.getApplicationContext();",
        "        File vm = new File(app.getApplicationInfo().nativeLibraryDir, \"libdartvm.so\");",
        "        if (!vm.isFile()) throw new IOException(\"The Dart VM is not part of this installation. Dart runs only on 64-bit ARM (arm64-v8a) devices.\");",
        "        File dir = new File(app.getFilesDir(), \"dart\");",
        "        if (!dir.isDirectory() && !dir.mkdirs()) throw new IOException(\"Could not create \" + dir);",
        "        File dill = new File(dir, \"main.dill\");",
        "        try (InputStream in = app.getAssets().open(\"dart/main.dill\"); OutputStream out = new FileOutputStream(dill)) {",
        "            byte[] buffer = new byte[32768];",
        "            int count;",
        "            while ((count = in.read(buffer)) != -1) out.write(buffer, 0, count);",
        "        }",
        "        ProcessBuilder builder = new ProcessBuilder(vm.getAbsolutePath(), dill.getAbsolutePath());",
        "        builder.directory(dir);",
        "        builder.environment().put(\"HOME\", dir.getAbsolutePath());",
        "        builder.environment().put(\"TMPDIR\", app.getCacheDir().getAbsolutePath());",
        "        builder.redirectErrorStream(true);",
        "        final Process process = builder.start();",
        "        final StudioDart dart = new StudioDart(process);",
        "        final Handler main = new Handler(Looper.getMainLooper());",
        "        Thread reader = new Thread(new Runnable() {",
        "            @Override public void run() {",
        "                try (BufferedReader lines = new BufferedReader(new InputStreamReader(process.getInputStream(), StandardCharsets.UTF_8))) {",
        "                    String line;",
        "                    while ((line = lines.readLine()) != null) {",
        "                        final String text = line;",
        "                        main.post(new Runnable() { @Override public void run() { if (listener != null) listener.onLine(text); } });",
        "                    }",
        "                } catch (IOException ignored) {",
        "                    // the process ended or was stopped",
        "                }",
        "                int code = -1;",
        "                try { code = process.waitFor(); } catch (InterruptedException interrupted) { Thread.currentThread().interrupt(); }",
        "                final int exit = code;",
        "                dart.writer.shutdown();",
        "                main.post(new Runnable() { @Override public void run() { if (listener != null) listener.onExit(exit); } });",
        "            }",
        "        }, \"studio-dart-output\");",
        "        reader.setDaemon(true);",
        "        reader.start();",
        "        return dart;",
        "    }",
        "",
        "    /** Writes one line to the standard input of the Dart program. */",
        "    public void send(final String line) {",
        "        try {",
        "            writer.execute(new Runnable() {",
        "                @Override public void run() {",
        "                    try {",
        "                        input.write((line + \"\\n\").getBytes(StandardCharsets.UTF_8));",
        "                        input.flush();",
        "                    } catch (IOException ignored) {",
        "                        // the program has ended",
        "                    }",
        "                }",
        "            });",
        "        } catch (java.util.concurrent.RejectedExecutionException ended) {",
        "            // the program has ended",
        "        }",
        "    }",
        "",
        "    public boolean isRunning() {",
        "        try { process.exitValue(); return false; } catch (IllegalThreadStateException running) { return true; }",
        "    }",
        "",
        "    /** Stops the Dart program. */",
        "    public void stop() { process.destroy(); }",
        "}",
        "");
}
